def merge_points(original: str, addition: str) -> str:
    """原文保留 + 追加补充(仅精确去重,不做子串判断——子串判断会误滤补充内容)。"""
    orig_points = [p.strip() for p in original.split("；") if p.strip() and p.strip() != "—"]
    for p in addition.split("；"):
        p = p.strip()
        if not p:
            continue
        if p not in orig_points:
            orig_points.append(p)
    return "；".join(orig_points)


def main():
    with open(TSV_PATH, encoding="utf-8") as f:
        rows = list(csv.DictReader(f, delimiter="\t"))

    enriched = 0
    for row in rows:
        name = row[COL_NAME].strip()
        if name not in ENRICHMENTS:
            continue
        row[COL_FEATURES] = merge_points(row[COL_FEATURES], ENRICHMENTS[name]["功能特点"])
        row[COL_SPECS] = merge_points(row[COL_SPECS], ENRICHMENTS[name]["规格参数"])
        enriched += 1

    with open(TSV_PATH, "w", encoding="utf-8", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=rows[0].keys(), delimiter="\t")
        writer.writeheader()
        writer.writerows(rows)

    print(f"补充完成: {enriched} 款商品(共 {len(rows)} 款)")
    print("剩余稀疏(<100字):")
    for r in rows:
        n = r[COL_NAME].strip()
        if len(r[COL_FEATURES]) + len(r[COL_SPECS]) < 100:
            print(f"  {n[:40]} | {len(r[COL_FEATURES])}/{len(r[COL_SPECS])}字")


if __name__ == "__main__":
    main()
